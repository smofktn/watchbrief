import assert from 'node:assert/strict'

export const verifyHome = async ({ checkpoint, evaluate, waitFor, navigate, reload, click, submit, token, fixture, stopDB, startDB }) => {
  const callHistoryBack = async () => {
    await evaluate('history.back()')
    await waitFor("location.pathname === '/home'")
  }
  checkpoint('deep-return')
  await navigate('/home')
  await waitFor("document.querySelector('#password') !== null")
  assert.equal(await evaluate('location.pathname'), '/login')
  await submit()
  await waitFor("document.querySelector('#home-title')?.textContent === 'ホーム'")
  const expectedReportLink = `section[aria-labelledby="home-title"] a[href=${JSON.stringify('/reports/' + fixture.home.report_id)}]`
  const rowFor = name => `Array.from(document.querySelectorAll('.home-collection')).find(row => row.querySelector('h3')?.textContent === ${JSON.stringify(name)})`
  const currentRow = rowFor('現在のCollection名（架空）')
  const otherRow = rowFor('架空コレクション')
  const emptyRow = rowFor('空の架空Collection')
  await waitFor(`document.querySelector(${JSON.stringify(expectedReportLink)}) !== null`)
  await waitFor(`(${currentRow})?.querySelector('.home-today-status')?.textContent.includes(${JSON.stringify(fixture.home.as_of_date + ' JST')})`)
  assert(await evaluate("document.querySelector('main').textContent.includes('現在のCollection名（架空）')"))
  assert(await evaluate(`document.querySelector(${JSON.stringify(expectedReportLink)}) !== null`))
  const currentCounts = await evaluate(`(${currentRow})?.querySelector('.home-today-status')?.textContent.replace(/\\s+/g, ' ').trim()`)
  assert.equal(currentCounts, `本日（${fixture.home.as_of_date} JST）：待機中 2件、実行中 1件、成功 2件、失敗 1件`)
  const otherCounts = await evaluate(`(${otherRow})?.querySelector('.home-today-status')?.textContent.replace(/\\s+/g, ' ').trim()`)
  assert.equal(otherCounts, `本日（${fixture.home.as_of_date} JST）：待機中 0件、実行中 0件、成功 1件、失敗 0件`)
  assert.equal(await evaluate(`document.querySelectorAll('.home-today-status').length`), 2)
  assert.equal(await evaluate(`(${emptyRow})?.querySelector('.home-today-status') === null`), true)
  assert(await evaluate("document.querySelector('main').textContent.includes('まだレポートはありません')"))
  checkpoint('database-outage')
  await stopDB()
  await click('更新')
  await waitFor("document.querySelector('main [role=alert]')?.textContent === '処理に失敗しました。時間をおいて再度お試しください'")
  assert(await evaluate("!document.querySelector('main').textContent.includes('現在のCollection名（架空）')"))
  assert.equal(await evaluate("document.querySelector('.home-today-status') === null"), true)
  await startDB()
  await click('ホームを再試行')
  await waitFor(`document.querySelector(${JSON.stringify(expectedReportLink)}) !== null`)
  await waitFor(`(${currentRow})?.querySelector('.home-today-status')?.textContent.includes(${JSON.stringify(fixture.home.as_of_date + ' JST')})`)
  checkpoint('report-detail')
  await evaluate(`document.querySelector(${JSON.stringify(expectedReportLink)}).click()`)
  await waitFor("document.querySelector('.report-body') !== null")
  assert(await evaluate("document.querySelector('main').textContent.includes('成功時の履歴名（架空）')"))
  checkpoint('reload-and-back')
  await callHistoryBack()
  await waitFor("location.pathname === '/home' && document.querySelector('#home-title')?.textContent === 'ホーム'")
  await reload()
  await waitFor(`location.pathname === '/home' && document.querySelector(${JSON.stringify(expectedReportLink)}) !== null`)
  await click('更新')
  await waitFor("document.querySelector('main').textContent.includes('現在のCollection名（架空）')")
  await waitFor(`(${currentRow})?.querySelector('.home-today-status')?.textContent.replace(/\\s+/g, ' ').trim() === ${JSON.stringify(`本日（${fixture.home.as_of_date} JST）：待機中 2件、実行中 1件、成功 2件、失敗 1件`)}`)
  const readHomeNames = () => evaluate("Array.from(document.querySelectorAll('.home-collection h3'), node => node.textContent)")
  const originalNames = fixture.home.order_names
  assert.deepEqual(await readHomeNames(), originalNames)
  const movedNames = [...originalNames]
  ;[movedNames[0], movedNames[1]] = [movedNames[1], movedNames[0]]
  const moveFirstDown = name => evaluate(`Array.from(document.querySelectorAll('.home-collection')).find(row=>row.querySelector('h3')?.textContent===${JSON.stringify(name)})?.querySelector('button[aria-label$="を下へ"]')?.click()`)
  const movedSelector = JSON.stringify(JSON.stringify(movedNames))
  await click('表示順を変更')
  assert.equal(await evaluate("document.querySelector('.home-collection button[aria-label$=を上へ]')?.disabled"), true)
  await moveFirstDown(originalNames[0])
  await waitFor(`JSON.stringify(Array.from(document.querySelectorAll('.home-collection h3'), node => node.textContent))===${JSON.stringify(JSON.stringify(movedNames))}`)
  await click('キャンセル')
  await waitFor(`JSON.stringify(Array.from(document.querySelectorAll('.home-collection h3'), node => node.textContent))===${JSON.stringify(JSON.stringify(originalNames))}`)
  await click('表示順を変更')
  await moveFirstDown(originalNames[0])
  await waitFor(`JSON.stringify(Array.from(document.querySelectorAll('.home-collection h3'), node => node.textContent))===${movedSelector}`)
  await click('順序を保存')
  await waitFor(`document.querySelector('button')?.textContent==='表示順を変更' && JSON.stringify(Array.from(document.querySelectorAll('.home-collection h3'), node => node.textContent))===${movedSelector}`)
  assert.equal(await evaluate("[...document.querySelectorAll('button')].some(button=>button.textContent==='順序を保存')"), false)
  await evaluate("document.querySelector('nav a[href=\\\"/collections\\\"]').click()")
  await waitFor("document.querySelector('#settings-title')?.textContent === 'コレクション設定'")
  await waitFor(`JSON.stringify(Array.from(document.querySelectorAll('.collection-settings ul li a'), node => node.textContent))===${movedSelector}`)
  await navigate('/home')
  await waitFor(`location.pathname === '/home' && JSON.stringify(Array.from(document.querySelectorAll('.home-collection h3'), node => node.textContent))===${movedSelector}`)
  assert(await evaluate(`document.querySelector(${JSON.stringify(expectedReportLink)}) !== null`))
  assert.equal(await evaluate(`(${currentRow})?.querySelector('.home-today-status')?.textContent.replace(/\\s+/g, ' ').trim()`), `本日（${fixture.home.as_of_date} JST）：待機中 2件、実行中 1件、成功 2件、失敗 1件`)
  checkpoint('logout')
  const activeToken = await token()
  assert(activeToken)
  await evaluate("window.baseFetch=window.fetch.bind(window);window.pauseNextHome=true;window.fetch=async(...args)=>{const response=await window.baseFetch(...args);if(new URL(args[0],location.href).pathname==='/api/home'&&window.pauseNextHome){window.pauseNextHome=false;return new Promise(resolve=>{window.releaseHome=()=>resolve(response)})}return response}")
  await click('更新')
  await waitFor("typeof window.releaseHome === 'function'")
  await click('ログアウト')
  await waitFor("document.querySelector('#password') !== null")
  await evaluate('window.releaseHome();window.releaseHome=undefined')
  await waitFor("document.querySelector('#password') !== null")
  assert(await evaluate("!document.querySelector('main').textContent.includes('現在のCollection名（架空）')"))
  assert.equal(await evaluate("document.querySelector('.home-today-status') === null"), true)
  assert.equal(await token(), undefined)
  assert.equal(await evaluate("localStorage.length === 0 && sessionStorage.length === 0"), true)
  return activeToken
}
