// Runs against a private disposable DB and generated credentials only.
import assert from 'node:assert/strict'

export const verifyTargets = async ({ checkpoint, call, evaluate, waitFor, navigate, click, submit, fixture, stopDB, startDB, token }) => {
  checkpoint('login')
  await navigate('/collections/' + fixture.ids.collection)
  await waitFor("document.querySelector('#password') !== null")
  await submit()
  await waitFor("[...document.querySelectorAll('button')].some(b=>b.textContent==='編集')")
  const cid = await evaluate(`(async()=>{const r=await fetch('/api/collections',{method:'POST',headers:{'Content-Type':'application/json','Idempotency-Key':crypto.randomUUID()},body:JSON.stringify({name:'対象編集用の架空設定',research_instruction:'',initial_lookback_mode:'ai',initial_lookback_days:null})});if(r.status!==201)throw Error('create failed');return(await r.json()).id})()`)
  const path = '/collections/' + cid
  await navigate(path)
  await waitFor("[...document.querySelectorAll('button')].some(b=>b.textContent==='編集')")
  await click('編集')
  const set = async (id, value) => evaluate(`{ const e=document.getElementById(${JSON.stringify(id)}); e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('input',{bubbles:true})); }`)
  await click('対象を追加')
  await click('保存')
  await waitFor("document.querySelector('#target-error-0') !== null")
  assert.equal(await evaluate('document.activeElement.id'), 'target-name-0')
  await set('target-name-0', '実画面の架空対象')
  await set('target-instruction-0', '改行\n架空の補足')
  await set('collection-name', '本体も同時保存')
  await call('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  assert(await evaluate('document.documentElement.scrollWidth<=innerWidth'))
  await call('Emulation.clearDeviceMetricsOverride')
  checkpoint('db-outage')
  stopDB()
  await click('保存')
  await waitFor("document.querySelector('form [role=alert]')?.textContent.includes('保存結果を確認できません')")
  assert.equal(await evaluate("document.querySelector('#target-name-0').value"), '実画面の架空対象')
  assert(await evaluate("[...document.querySelectorAll('fieldset')].every(e=>e.disabled)"))
  startDB()
  checkpoint('response-loss')
  await evaluate("window.targetFetch=window.fetch.bind(window);window.targetRequests=[];window.dropTargetResponse=true;window.fetch=async(...args)=>{if(args[1]?.method==='PATCH'){window.targetRequests.push({body:args[1].body,key:args[1].headers['Idempotency-Key']});const r=await window.targetFetch(...args);if(window.dropTargetResponse){window.dropTargetResponse=false;await r.text();throw new TypeError('fictional lost response')}return r}return window.targetFetch(...args)}")
  await click('同じ内容で再試行')
  await waitFor("document.querySelector('form [role=alert]')?.textContent.includes('接続できず保存結果')")
  await click('同じ内容で再試行')
  await waitFor("document.querySelector('#edit-title')===null && document.querySelector('main').textContent.includes('実画面の架空対象')")
  assert(await evaluate("window.targetRequests.length===2 && window.targetRequests[0].body===window.targetRequests[1].body && window.targetRequests[0].key===window.targetRequests[1].key"))
  await evaluate('window.fetch=window.targetFetch')
  await navigate(path)
  await waitFor("document.querySelector('main').textContent.includes('実画面の架空対象')")
  assert(await evaluate(`(async()=>{const c=await(await fetch('/api${path}')).json();return c.targets.length===1 && c.targets[0].enabled && !c.enabled && c.version==='2'})()`))
  checkpoint('edit-reload')
  await click('編集')
  await set('target-name-0', '編集後の架空対象')
  await click('保存')
  await waitFor("document.querySelector('#edit-title')===null && document.querySelector('main').textContent.includes('編集後の架空対象')")
  await navigate(path)
  await waitFor("document.querySelector('main').textContent.includes('編集後の架空対象')")
  await click('編集')
  await click('対象を追加')
  await set('target-name-1', '競合時に残す新規下書き')
  await set('target-instruction-0', '競合時に残す編集')
  checkpoint('conflict')
  assert.equal(await evaluate(`(async()=>{const c=await(await fetch('/api${path}')).json();return(await fetch('/api${path}',{method:'PATCH',headers:{'Content-Type':'application/json','Idempotency-Key':crypto.randomUUID()},body:JSON.stringify({name:c.name,research_instruction:c.research_instruction,initial_lookback_mode:c.initial_lookback_mode,initial_lookback_days:c.initial_lookback_days,version:c.version,targets:[{id:c.targets[0].id,name:'先行保存した対象',instruction:''}]})})).status})()`), 200)
  await click('保存')
  await waitFor("[...document.querySelectorAll('button')].some(b=>b.textContent==='最新値を確認')")
  assert.equal(await evaluate("document.querySelector('#target-name-1').value"), '競合時に残す新規下書き')
  await click('最新値を確認')
  await waitFor("document.querySelector('.latest-settings')?.textContent.includes('先行保存した対象')")
  await click('最新値で編集し直す')
  assert.equal(await evaluate("document.querySelector('#target-name-0').value"), '先行保存した対象')
  assert(await evaluate("document.querySelector('#target-name-1')===null"))
  await click('対象を追加')
  await set('target-name-1', '取り消す未保存対象')
  await click('追加を取り消す')
  assert(await evaluate("document.querySelector('#target-name-1')===null"))
  await click('対象を追加')
  await set('target-name-1', '失効で消す対象')
  checkpoint('session-expiry')
  assert.equal(await evaluate("(async()=> (await fetch('/api/logout',{method:'POST'})).status)()"), 204)
  await click('保存')
  await waitFor("document.querySelector('#password')!==null")
  assert(await evaluate("!document.querySelector('main').textContent.includes('失効で消す対象')"))
  await submit()
  await waitFor("[...document.querySelectorAll('button')].some(b=>b.textContent==='編集')")
  await click('編集')
  await click('対象を追加')
  await set('target-name-1', 'ログアウトで消す対象')
  const issuedToken = await token()
  await click('ログアウト')
  await waitFor("document.querySelector('#password')!==null")
  assert(await evaluate("document.querySelector('#target-name-1')===null && localStorage.length===0 && sessionStorage.length===0"))
  console.log('Target browser: add/save/reload/edit, combined body, validation/focus/mobile, DB outage, committed response loss/retry, whole conflict/reset, cancel new draft, session expiry and logout: passed')
  return issuedToken
}
