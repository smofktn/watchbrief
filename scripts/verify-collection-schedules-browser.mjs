// Only called with the disposable project's private fixture.
import assert from 'node:assert/strict'
export const verifySchedules = async ({ checkpoint, call, evaluate, waitFor, navigate, click, submit, stopDB, startDB, token }) => {
  checkpoint('login')
  await navigate('/collections')
  await waitFor("document.querySelector('#password')!==null")
  await submit()
  await waitFor("document.querySelector('main a[href=\"/collections/new\"]')!==null")
  const cid = await evaluate(`(async()=>{const r=await fetch('/api/collections',{method:'POST',headers:{'Content-Type':'application/json','Idempotency-Key':crypto.randomUUID()},body:JSON.stringify({name:'Schedule編集用の架空設定',research_instruction:'',initial_lookback_mode:'ai',initial_lookback_days:null})});return(await r.json()).id})()`)
  const path = '/collections/' + cid
  const set = async (selector, value) => evaluate(`{const e=document.querySelector(${JSON.stringify(selector)});e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('input',{bubbles:true}));}`)
  await navigate(path)
  await waitFor("[...document.querySelectorAll('button')].some(b=>b.textContent==='編集')")
  await click('編集')
  await set('#collection-name','未設定でも本体保存')
  await click('保存')
  await waitFor("document.querySelector('#edit-title')===null && document.querySelector('main').textContent.includes('未設定でも本体保存')")
  assert(await evaluate(`(async()=> (await(await fetch('/api${path}')).json()).schedule===null)()`))
  await click('編集')
  await set('#schedule-cron','0 24 * * *')
  await click('保存')
  assert(await evaluate("document.querySelector('#schedule-error')!==null && document.activeElement.id==='schedule-cron' && document.querySelector('#schedule-cron').value==='0 24 * * *'"))
  await set('#schedule-cron','0 7 * * *')
  await set('#collection-name','Scheduleと本体同時保存')
  await call('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true})
  assert(await evaluate('document.documentElement.scrollWidth<=innerWidth'))
  await call('Emulation.clearDeviceMetricsOverride')
  checkpoint('db-outage')
  stopDB()
  await click('保存')
  await waitFor("document.querySelector('form [role=alert]')?.textContent.includes('保存結果を確認できません')")
  assert(await evaluate("document.querySelector('#schedule-cron').value==='0 7 * * *' && [...document.querySelectorAll('fieldset')].every(e=>e.disabled)"))
  startDB()
  checkpoint('committed-response-loss')
  await evaluate("window.scheduleFetch=window.fetch.bind(window);window.scheduleRequests=[];window.dropScheduleResponse=true;window.fetch=async(...args)=>{if(args[1]?.method==='PATCH'){window.scheduleRequests.push({body:args[1].body,key:args[1].headers['Idempotency-Key']});const r=await window.scheduleFetch(...args);if(window.dropScheduleResponse){window.dropScheduleResponse=false;await r.text();throw new TypeError('fictional lost response')}return r}return window.scheduleFetch(...args)}")
  await click('同じ内容で再試行')
  await waitFor("document.querySelector('form [role=alert]')?.textContent.includes('接続できず保存結果')")
  await click('同じ内容で再試行')
  await waitFor("document.querySelector('#edit-title')===null && document.querySelector('main').textContent.includes('0 7 * * *')")
  assert(await evaluate('window.scheduleRequests.length===2 && window.scheduleRequests[0].body===window.scheduleRequests[1].body && window.scheduleRequests[0].key===window.scheduleRequests[1].key'))
  await evaluate('window.fetch=window.scheduleFetch')
  await navigate(path)
  await waitFor("document.querySelector('main').textContent.includes('0 7 * * *')")
  assert(await evaluate(`(async()=>{const c=await(await fetch('/api${path}')).json();return !c.enabled && c.version==='3' && c.schedule.cron_expression==='0 7 * * *'})()`))
  checkpoint('edit-and-reload')
  await click('編集')
  await set('#schedule-cron','')
  await click('保存')
  assert(await evaluate("document.querySelector('#schedule-error')?.textContent.includes('空にできません')"))
  await set('#schedule-cron','0 7,19 * * *')
  await click('保存')
  await waitFor("document.querySelector('#edit-title')===null && document.querySelector('main').textContent.includes('0 7,19 * * *')")
  await navigate(path)
  await waitFor("document.querySelector('main').textContent.includes('0 7,19 * * *')")
  checkpoint('conflict')
  await click('編集')
  await set('#collection-name','競合で保持する本体')
  await set('#schedule-cron','0 8 * * *')
  assert.equal(await evaluate(`(async()=>{const c=await(await fetch('/api${path}')).json();return(await fetch('/api${path}',{method:'PATCH',headers:{'Content-Type':'application/json','Idempotency-Key':crypto.randomUUID()},body:JSON.stringify({name:c.name,research_instruction:c.research_instruction,initial_lookback_mode:c.initial_lookback_mode,initial_lookback_days:c.initial_lookback_days,version:c.version,schedule:{...c.schedule,cron_expression:'0 9 * * *'}})})).status})()`),200)
  await click('保存')
  await waitFor("[...document.querySelectorAll('button')].some(b=>b.textContent==='最新値を確認')")
  assert(await evaluate("document.querySelector('#schedule-cron').value==='0 8 * * *' && document.querySelector('#collection-name').value==='競合で保持する本体'"))
  await click('最新値を確認')
  await waitFor("document.querySelector('.latest-settings')?.textContent.includes('0 9 * * *')")
  assert(await evaluate("document.querySelector('#schedule-cron').value==='0 8 * * *'"))
  await click('最新値で編集し直す')
  assert(await evaluate("document.querySelector('#schedule-cron').value==='0 9 * * *' && document.querySelector('#collection-name').value==='Scheduleと本体同時保存'"))
  checkpoint('session-expiry')
  await set('#schedule-cron','0 10 * * *')
  assert.equal(await evaluate("(async()=> (await fetch('/api/logout',{method:'POST'})).status)()"),204)
  await click('保存')
  await waitFor("document.querySelector('#password')!==null")
  assert(await evaluate("document.querySelector('#schedule-cron')===null"))
  await submit()
  await waitFor("[...document.querySelectorAll('button')].some(b=>b.textContent==='編集')")
  await click('編集')
  await set('#schedule-cron','0 11 * * *')
  const issuedToken = await token()
  await click('ログアウト')
  await waitFor("document.querySelector('#password')!==null")
  assert(await evaluate("document.querySelector('#schedule-cron')===null && localStorage.length===0 && sessionStorage.length===0"))
  console.log('Schedule browser: unset/save, add/save/reload/edit, invalid/empty validation/focus/mobile, real DB outage, committed fetch-response loss/exact retry, schedule conflict/compare/restart, session expiry/logout: passed')
  return issuedToken
}
