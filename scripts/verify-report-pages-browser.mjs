// The outer runner supplies only fictional credentials and its disposable DB.
import assert from 'node:assert/strict'
export const verifyPages = async ({ checkpoint, evaluate, waitFor, navigate, click, submit, stopDB, startDB, token }) => {
  const count = () => evaluate("document.querySelectorAll('main a[href^=\"/reports/\"]:not([href=\"/reports/daily\"]):not([href=\"/reports/collections\"])').length")
  const more = "[...document.querySelectorAll('button')].some(b=>b.textContent==='もっと読む')"
  checkpoint('login-and-first-30')
  await navigate('/reports')
  await waitFor("document.querySelector('#password')!==null")
  await submit()
  await waitFor(more)
  assert.equal(await count(),30)
  const firstIDs=await evaluate("[...document.querySelectorAll('main a[href^=\"/reports/\"]:not([href=\"/reports/daily\"]):not([href=\"/reports/collections\"])')].map(a=>a.getAttribute('href'))")
  checkpoint('db-outage-retains-page')
  stopDB()
  await click('もっと読む')
  await waitFor("document.querySelector('main [role=alert]')?.textContent.includes('同じ続きから再試行')")
  assert.equal(await count(),30)
  assert(await evaluate("[...document.querySelectorAll('button')].find(b=>b.textContent==='もっと読む').disabled===false"))
  startDB()
  checkpoint('double-click-and-remaining-5')
  await evaluate("window.pageFetch=window.fetch.bind(window);window.pageRequests=[];window.holdNext=true;window.fetch=async(...args)=>{if(typeof args[0]==='string'&&args[0].startsWith('/api/reports?')){window.pageRequests.push(args[0]);const response=await window.pageFetch(...args);if(window.holdNext){window.holdNext=false;return new Promise(resolve=>{window.releasePage=()=>resolve(response)})}return response}return window.pageFetch(...args)}")
  await click('もっと読む')
  await waitFor("typeof window.releasePage==='function'")
  await click('もっと読む')
  assert.equal(await evaluate('window.pageRequests.length'),1)
  assert.equal(await count(),30)
  await evaluate('window.releasePage();window.releasePage=undefined')
  await waitFor("document.querySelector('main').textContent.includes('すべての保存済みReportを表示しました')")
  assert.equal(await count(),35)
  const allIDs=await evaluate("[...document.querySelectorAll('main a[href^=\"/reports/\"]:not([href=\"/reports/daily\"]):not([href=\"/reports/collections\"])')].map(a=>a.getAttribute('href'))")
  assert.equal(new Set(allIDs).size,35)
  assert.deepEqual(allIDs.slice(0,30),firstIDs)
  checkpoint('safe-detail-and-reset')
  await evaluate("document.querySelector('main a[href^=\"/reports/\"]:not([href=\"/reports/daily\"]):not([href=\"/reports/collections\"])').click()")
  await waitFor("document.querySelector('.report-body h1')!==null")
  assert(await evaluate("!document.querySelector('.report-body script,.report-body img') && window.reportExecuted===undefined"))
  await evaluate("document.querySelector('nav a[href=\"/reports\"]').click()")
  await waitFor(more)
  assert.equal(await count(),30)
  await navigate('/reports')
  await waitFor(more)
  assert.equal(await count(),30)
  checkpoint('late-route')
  const hold = () => evaluate("window.pageFetch=window.fetch.bind(window);window.holdNext=true;window.fetch=async(...args)=>{const response=await window.pageFetch(...args);if(typeof args[0]==='string'&&args[0].startsWith('/api/reports?')&&window.holdNext){window.holdNext=false;return new Promise(resolve=>{window.releasePage=()=>resolve(response)})}return response}")
  await hold()
  await click('もっと読む')
  await waitFor("typeof window.releasePage==='function'")
  await evaluate("document.querySelector('nav a[href=\"/me\"]').click()")
  await waitFor("location.pathname==='/me' && document.querySelector('#current-user-title')!==null")
  await evaluate('window.releasePage();window.releasePage=undefined')
  await evaluate('new Promise(resolve=>setTimeout(resolve,150))')
  assert.equal(await count(),0)
  assert(await evaluate('!'+more))
  checkpoint('late-logout')
  await navigate('/reports')
  await waitFor(more)
  await hold()
  await click('もっと読む')
  await waitFor("typeof window.releasePage==='function'")
  const issued=await token()
  await click('ログアウト')
  await waitFor("document.querySelector('#password')!==null")
  await evaluate('window.releasePage();window.releasePage=undefined')
  await evaluate('new Promise(resolve=>setTimeout(resolve,150))')
  assert.equal(await count(),0)
  assert(await evaluate("localStorage.length===0 && sessionStorage.length===0 && !document.querySelector('.report-body')"))
  checkpoint('continuation-401')
  await navigate('/reports')
  await waitFor("document.querySelector('#password')!==null")
  await submit()
  await waitFor(more)
  assert.equal(await evaluate("(async()=> (await fetch('/api/logout',{method:'POST'})).status)()"),204)
  await click('もっと読む')
  await waitFor("document.querySelector('#password')!==null")
  assert.equal(await evaluate('location.pathname+location.search'),'/login?return_to=%2Freports')
  assert.equal(await count(),0)
  console.log('Report pages browser: login/30+5/end, no duplicates, actual DB outage/recovery, double operation, safe Markdown detail, return/reload reset, late route/logout discard and continuation401 clearing: passed')
  return issued
}
