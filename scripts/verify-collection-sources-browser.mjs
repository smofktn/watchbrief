// Runs only with the private disposable project's generated credentials.
import assert from 'node:assert/strict'
export const verifySources = async ({ checkpoint, call, evaluate, waitFor, navigate, click, submit, fixture, stopDB, startDB, token }) => {
  checkpoint('login')
  await navigate('/collections/' + fixture.ids.collection)
  await waitFor("document.querySelector('#password')!==null")
  await submit()
  await waitFor("[...document.querySelectorAll('button')].some(b=>b.textContent==='編集')")
  const cid = await evaluate(`(async()=>{const r=await fetch('/api/collections',{method:'POST',headers:{'Content-Type':'application/json','Idempotency-Key':crypto.randomUUID()},body:JSON.stringify({name:'情報源編集用の架空設定',research_instruction:'',initial_lookback_mode:'ai',initial_lookback_days:null})});const c=await r.json();await fetch('/api/collections/'+c.id,{method:'PATCH',headers:{'Content-Type':'application/json','Idempotency-Key':crypto.randomUUID()},body:JSON.stringify({name:'情報源編集用の架空設定',research_instruction:'',initial_lookback_mode:'ai',initial_lookback_days:null,version:'1',targets:[{id:null,name:'保存済み架空対象',instruction:''}]})});return c.id})()`)
  const path = '/collections/' + cid
  const set = async (selector, value) => evaluate(`{const e=document.querySelector(${JSON.stringify(selector)});e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('input',{bubbles:true}));}`)
  const sourceName = 'input[id^="source-name-"]'
  const sourceURL = 'input[id^="source-url-"]'
  const sourceInstruction = 'textarea[id^="source-instruction-"]'
  await navigate(path)
  await waitFor("[...document.querySelectorAll('button')].some(b=>b.textContent==='編集')")
  await click('編集')
  await click('情報源を追加')
  await click('保存')
  await waitFor("document.querySelector('[id^=source-error-]')!==null")
  assert(await evaluate("document.activeElement.id.startsWith('source-name-')"))
  await set(sourceName,'<b>架空公式サイト</b>')
  await set(sourceURL,'https://user:password@example.com')
  await click('保存')
  assert(await evaluate("document.querySelector('[id^=source-error-]').textContent.includes('認証情報')"))
  await set(sourceURL,'https://EXAMPLE.com/news?q=日本語#発表')
  await set(sourceInstruction,'改行\n架空情報源の指示')
  await set('#collection-name','本体と情報源を同時保存')
  await set('#target-name-0','対象も同時保存')
  await call('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true})
  assert(await evaluate('document.documentElement.scrollWidth<=innerWidth'))
  await call('Emulation.clearDeviceMetricsOverride')
  checkpoint('db-outage')
  stopDB()
  await click('保存')
  await waitFor("document.querySelector('form [role=alert]')?.textContent.includes('保存結果を確認できません')")
  assert.equal(await evaluate(`document.querySelector(${JSON.stringify(sourceName)}).value`),'<b>架空公式サイト</b>')
  assert(await evaluate("[...document.querySelectorAll('fieldset')].every(e=>e.disabled)"))
  startDB()
  checkpoint('committed-response-loss')
  await evaluate("window.sourceFetch=window.fetch.bind(window);window.sourceRequests=[];window.dropSourceResponse=true;window.fetch=async(...args)=>{if(args[1]?.method==='PATCH'){window.sourceRequests.push({body:args[1].body,key:args[1].headers['Idempotency-Key']});const r=await window.sourceFetch(...args);if(window.dropSourceResponse){window.dropSourceResponse=false;await r.text();throw new TypeError('fictional lost response')}return r}return window.sourceFetch(...args)}")
  await click('同じ内容で再試行')
  await waitFor("document.querySelector('form [role=alert]')?.textContent.includes('接続できず保存結果')")
  await click('同じ内容で再試行')
  await waitFor("document.querySelector('#edit-title')===null && document.querySelector('main').textContent.includes('<b>架空公式サイト</b>')")
  assert(await evaluate('window.sourceRequests.length===2 && window.sourceRequests[0].body===window.sourceRequests[1].body && window.sourceRequests[0].key===window.sourceRequests[1].key'))
  await evaluate('window.fetch=window.sourceFetch')
  await navigate(path)
  await waitFor("document.querySelector('main').textContent.includes('<b>架空公式サイト</b>')")
  assert(await evaluate("document.querySelector('main b')===null && document.querySelector('main a[href^=http]')===null"))
  assert(await evaluate(`(async()=>{const c=await(await fetch('/api${path}')).json();return c.targets[0].sources.length===1 && c.targets[0].sources[0].url==='https://EXAMPLE.com/news?q=日本語#発表' && c.version==='3'})()`))
  checkpoint('edit-and-reload')
  await click('編集')
  await set(sourceName,'編集後の架空情報源')
  await set(sourceURL,'http://example.com/edited')
  await click('保存')
  await waitFor("document.querySelector('#edit-title')===null && document.querySelector('main').textContent.includes('編集後の架空情報源')")
  await navigate(path)
  await waitFor("document.querySelector('main').textContent.includes('http://example.com/edited')")
  checkpoint('conflict')
  await click('編集')
  await set(sourceName,'競合で保持する情報源')
  await click('情報源を追加')
  const names = await evaluate("[...document.querySelectorAll('input[id^=source-name-]')].map(e=>e.id)")
  const urls = await evaluate("[...document.querySelectorAll('input[id^=source-url-]')].map(e=>e.id)")
  await set('#'+names[1],'競合で保持する新規情報源')
  await set('#'+urls[1],'https://example.com/new')
  assert.equal(await evaluate(`(async()=>{const c=await(await fetch('/api${path}')).json();return(await fetch('/api${path}',{method:'PATCH',headers:{'Content-Type':'application/json','Idempotency-Key':crypto.randomUUID()},body:JSON.stringify({name:c.name,research_instruction:c.research_instruction,initial_lookback_mode:c.initial_lookback_mode,initial_lookback_days:c.initial_lookback_days,version:c.version,sources:[{...c.targets[0].sources[0],watch_target_id:c.targets[0].id,name:'先行保存した情報源'}]})})).status})()`),200)
  await click('保存')
  await waitFor("[...document.querySelectorAll('button')].some(b=>b.textContent==='最新値を確認')")
  assert.equal(await evaluate(`document.querySelector(${JSON.stringify(sourceName)}).value`),'競合で保持する情報源')
  await click('最新値を確認')
  await waitFor("document.querySelector('.latest-settings')?.textContent.includes('先行保存した情報源')")
  assert(await evaluate(`document.querySelector('#${names[1]}').value==='競合で保持する新規情報源'`))
  await click('最新値で編集し直す')
  assert.equal(await evaluate(`document.querySelector(${JSON.stringify(sourceName)}).value`),'先行保存した情報源')
  assert.equal(await evaluate("document.querySelectorAll('input[id^=source-name-]').length"),1)
  await click('情報源を追加')
  await click('情報源の追加を取り消す')
  assert.equal(await evaluate("document.querySelectorAll('input[id^=source-name-]').length"),1)
  await click('対象を追加')
  assert(await evaluate("document.querySelector('main').textContent.includes('対象を保存してから情報源を追加')"))
  await click('追加を取り消す')
  checkpoint('session-expiry')
  await set(sourceName,'失効時に消す情報源')
  assert.equal(await evaluate("(async()=> (await fetch('/api/logout',{method:'POST'})).status)()"),204)
  await click('保存')
  await waitFor("document.querySelector('#password')!==null")
  assert(await evaluate("!document.querySelector('main').textContent.includes('失効時に消す情報源')"))
  await submit()
  await waitFor("[...document.querySelectorAll('button')].some(b=>b.textContent==='編集')")
  await click('編集')
  await set(sourceName,'ログアウトで消す情報源')
  const issuedToken = await token()
  await click('ログアウト')
  await waitFor("document.querySelector('#password')!==null")
  assert(await evaluate("document.querySelector('input[id^=source-name-]')===null && localStorage.length===0 && sessionStorage.length===0"))
  console.log('Source browser: add/save/reload/edit, combined body/target, text-only URL, validation/focus/mobile, real DB outage, committed response loss/exact retry, source conflict/compare/reset, cancellation, session expiry/logout: passed')
  return issuedToken
}
