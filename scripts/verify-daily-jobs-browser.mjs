// The outer runner supplies only fictional credentials and its disposable DB.
import assert from 'node:assert/strict'
export const verifyDaily = async ({ checkpoint, changeDailyState, call, evaluate, waitFor, navigate, click, submit, stopDB, startDB, token }) => {
  const count = () => evaluate("document.querySelectorAll('.daily-job').length")
  const more = "[...document.querySelectorAll('button')].some(b=>b.textContent==='もっと読む')"
  checkpoint('browser-emulation')
  await call('Emulation.setTimezoneOverride', { timezoneId: 'America/Los_Angeles' })
  checkpoint('login-and-first-30')
  await navigate('/reports/daily')
  await waitFor("document.querySelector('#password')!==null")
  await submit()
  await waitFor(more)
  assert.equal(await count(),30)
  assert.deepEqual(await evaluate("[...new Set([...document.querySelectorAll('.job-status')].map(e=>e.textContent))].sort()"), ['失敗','実行中','待機中','成功'].sort())
  assert(await evaluate("[...document.querySelectorAll('.daily-job')].every(e=>e.querySelector('.job-status').textContent==='成功' ? e.querySelectorAll('a').length===1 : e.querySelectorAll('a').length===0)"))
  const firstIDs=await evaluate("[...document.querySelectorAll('.daily-job')].map(a=>a.textContent)")
  checkpoint('db-outage-retains-page')
  stopDB()
  await click('もっと読む')
  await waitFor("document.querySelector('main [role=alert]')?.textContent.includes('同じ続きから再試行')")
  assert.equal(await count(),30)
  assert(await evaluate("[...document.querySelectorAll('button')].find(b=>b.textContent==='もっと読む').disabled===false"))
  startDB()
  checkpoint('double-click-and-remaining-5')
  await evaluate("window.pageFetch=window.fetch.bind(window);window.pageRequests=[];window.holdNext=true;window.fetch=async(...args)=>{if(typeof args[0]==='string'&&args[0].startsWith('/api/generation-jobs?')){window.pageRequests.push(args[0]);const response=await window.pageFetch(...args);if(window.holdNext){window.holdNext=false;return new Promise(resolve=>{window.releasePage=()=>resolve(response)})}return response}return window.pageFetch(...args)}")
  await click('もっと読む')
  await waitFor("typeof window.releasePage==='function'")
  await click('もっと読む')
  assert.equal(await evaluate('window.pageRequests.length'),1)
  assert.equal(await count(),30)
  await evaluate('window.releasePage();window.releasePage=undefined')
  await waitFor("document.querySelector('main').textContent.includes('すべての保存済み予定・結果を表示しました')")
  assert.equal(await count(),35)
  const allIDs=await evaluate("[...document.querySelectorAll('.daily-job')].map(a=>a.textContent)")
  assert.equal(new Set(allIDs).size,35)
  assert.deepEqual(allIDs.slice(0,30),firstIDs)
  assert.deepEqual(await evaluate("[...document.querySelectorAll('.job-day h3')].map(e=>e.textContent)"), ['2026/04/02','2026/04/01'])
  assert.equal(await evaluate("document.querySelector('.daily-job time').textContent"),'00:00:00')
  checkpoint('mobile-width')
  await call('Emulation.setDeviceMetricsOverride', { width:390, height:844, deviceScaleFactor:1, mobile:false })
  assert(await evaluate('document.documentElement.scrollWidth<=innerWidth'))
  await call('Emulation.clearDeviceMetricsOverride')
  checkpoint('safe-detail-and-reset')
  await evaluate("document.querySelector('.daily-job a').click()")
  await waitFor("document.querySelector('.report-body h1')!==null")
  assert(await evaluate("!document.querySelector('.report-body script,.report-body img') && window.reportExecuted===undefined"))
  await navigate('/reports/daily')
  await waitFor(more)
  assert.equal(await count(),30)
  await navigate('/reports/daily')
  await waitFor(more)
  assert.equal(await count(),30)
  checkpoint('invalid-success-and-refresh')
  await evaluate("window.dailyOriginal=window.fetch.bind(window);window.fetch=(...args)=>typeof args[0]==='string'&&args[0].startsWith('/api/generation-jobs?')?Promise.resolve(new Response('{}',{status:200})):window.dailyOriginal(...args)")
  await click('もっと読む')
  await waitFor("document.querySelector('main [role=alert]')?.textContent.includes('同じ続きから再試行')")
  assert.equal(await count(),30)
  await evaluate("window.fetch=window.dailyOriginal")
  await click('更新')
  await waitFor(more)
  assert.equal(await count(),30)
  checkpoint('manual-refresh-reads-state')
  const stateOfTwo = "[...document.querySelectorAll('.daily-job')].find(e=>e.textContent.includes('日付別検証（架空）2 '))?.querySelector('.job-status')?.textContent"
  assert.equal(await evaluate(stateOfTwo),'実行中')
  try {
    changeDailyState(true)
    assert.equal(await evaluate(stateOfTwo),'実行中')
    await click('更新')
    await waitFor(stateOfTwo+"==='失敗'")
    assert.equal(await count(),30)
  } finally {
    changeDailyState(false)
  }
  await click('更新')
  await waitFor(stateOfTwo+"==='実行中'")
  checkpoint('late-route')
  const hold = () => evaluate("window.pageFetch=window.fetch.bind(window);window.holdNext=true;window.fetch=async(...args)=>{const response=await window.pageFetch(...args);if(typeof args[0]==='string'&&args[0].startsWith('/api/generation-jobs?')&&window.holdNext){window.holdNext=false;return new Promise(resolve=>{window.releasePage=()=>resolve(response)})}return response}")
  await hold()
  await click('もっと読む')
  await waitFor("typeof window.releasePage==='function'")
  await evaluate("document.querySelector('nav a[href=\"/me\"]').click()")
  await waitFor("location.pathname==='/me' && document.querySelector('#current-user-title')!==null")
  await evaluate('window.releasePage();window.releasePage=undefined')
  await evaluate('new Promise(resolve=>setTimeout(resolve,150))')
  assert.equal(await count(),0)
  assert(await evaluate('!'+more))
  checkpoint('late-logout')
  await navigate('/reports/daily')
  await waitFor(more)
  await hold()
  await click('もっと読む')
  await waitFor("typeof window.releasePage==='function'")
  const issued=await token()
  await click('ログアウト')
  await waitFor("document.querySelector('#password')!==null")
  await evaluate('window.releasePage();window.releasePage=undefined')
  await evaluate('new Promise(resolve=>setTimeout(resolve,150))')
  assert.equal(await count(),0)
  assert(await evaluate("localStorage.length===0 && sessionStorage.length===0 && !document.querySelector('.report-body')"))
  checkpoint('continuation-401')
  await navigate('/reports/daily')
  await waitFor("document.querySelector('#password')!==null")
  await submit()
  await waitFor(more)
  assert.equal(await evaluate("(async()=> (await fetch('/api/logout',{method:'POST'})).status)()"),204)
  await click('もっと読む')
  await waitFor("document.querySelector('#password')!==null")
  assert.equal(await evaluate('location.pathname+location.search'),'/login?return_to=%2Freports%2Fdaily')
  assert.equal(await count(),0)
  console.log('Daily Jobs browser: login/30+5/end, no duplicates, actual DB outage/recovery, double operation, safe Markdown detail, return/reload reset, late route/logout discard and continuation401 clearing: passed')
  return issued
}
