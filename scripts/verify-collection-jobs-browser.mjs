// Exercises the Collection-specific report path in the outer runner's disposable app.
import assert from 'node:assert/strict'

export const verifyCollectionJobs = async ({ checkpoint, evaluate, waitFor, navigate, click, submit, stopDB, startDB, fixture }) => {
  const path = '/reports/collections/' + fixture.ids.collection
  const rows = () => evaluate("document.querySelectorAll('.collection-job').length")
  checkpoint('deep-return-and-four-states')
  await navigate(path)
  await waitFor("document.querySelector('#password')!==null")
  assert.equal(await evaluate('location.pathname+location.search'), '/login?return_to='+encodeURIComponent(path))
  await submit()
  await waitFor("document.querySelectorAll('.collection-job').length===4")
  assert.deepEqual(await evaluate("[...document.querySelectorAll('.collection-job')].map(e=>e.textContent.match(/待機中|実行中|成功|失敗/)?.[0]).sort()"), ['失敗','実行中','待機中','成功'].sort())
  assert.equal(await evaluate("[...document.querySelectorAll('.collection-job')].filter(e=>e.querySelector('a')).length"),1)
  assert.equal(await evaluate("document.querySelector('.collection-job time').textContent.includes('2026/04/02')"),true)
  assert.equal(await evaluate("document.querySelector('.collection-job time').textContent.includes('00:00:')"),true)
  checkpoint('success-detail-and-reload')
  await evaluate("document.querySelector('.collection-job a').click()")
  await waitFor("document.querySelector('.report-body h1')!==null")
  await navigate(path)
  await waitFor("document.querySelectorAll('.collection-job').length===4")
  await click('更新')
  await waitFor("document.querySelectorAll('.collection-job').length===4")
  checkpoint('switch-discards-old-response')
  const next = await evaluate(`(async()=>{const r=await fetch('/api/collections');const d=await r.json();return d.collections.find(c=>c.id!==${JSON.stringify(fixture.ids.collection)})?.id})()`)
  assert(next)
  await evaluate(`window.collectionFetch=window.fetch.bind(window);window.holdCollection=true;window.fetch=async(...args)=>{const response=await window.collectionFetch(...args);if(typeof args[0]==='string'&&args[0].includes('/api/collections/${fixture.ids.collection}/generation-jobs')&&window.holdCollection){window.holdCollection=false;return new Promise(resolve=>{window.releaseCollection=()=>resolve(response)})}return response}`)
  await click('更新')
  await waitFor("typeof window.releaseCollection==='function'")
  await evaluate(`(()=>{const s=document.querySelector('#collection-jobs-choice');s.value=${JSON.stringify(next)};s.dispatchEvent(new Event('change',{bubbles:true}))})()`)
  await waitFor(`location.pathname==='/reports/collections/${next}'`)
  await evaluate('window.releaseCollection();window.releaseCollection=undefined')
  await waitFor("document.querySelector('#collection-jobs-choice')?.value!==''")
  await evaluate('new Promise(resolve=>setTimeout(resolve,120))')
  assert.equal(await rows(),0)
  checkpoint('outage-and-retry')
  // Select the fixture Collection again and prove real DB outage recovery preserves a
  // safe error state without displaying stale private history.
  await evaluate(`(()=>{const s=document.querySelector('#collection-jobs-choice');s.value=${JSON.stringify(fixture.ids.collection)};s.dispatchEvent(new Event('change',{bubbles:true}))})()`)
  await waitFor(`location.pathname===${JSON.stringify(path)} && document.querySelectorAll('.collection-job').length===4`)
  stopDB()
  await click('更新')
  await waitFor("document.querySelector('main [role=alert]')!==null")
  assert.equal(await rows(),0)
  startDB()
  await click('再試行')
  await waitFor("document.querySelectorAll('.collection-job').length===4")
  checkpoint('logout-clears-private-history')
  await click('ログアウト')
  await waitFor("document.querySelector('#password')!==null")
  assert.equal(await rows(),0)
  assert(await evaluate('localStorage.length===0&&sessionStorage.length===0'))
  console.log('Collection Jobs browser: protected deep return, four states/JST/success-only link, saved Report, reload/refresh, delayed switch discard, real DB outage/recovery, logout clearing: passed')
}
