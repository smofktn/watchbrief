// Uses the existing disposable DB and private Chromium driver.
import assert from 'node:assert/strict'

export const verifyUpdate = async ({ checkpoint = () => {}, call, evaluate, waitFor, navigate, click, submit, fixture, stopDB, startDB, token }) => {
  checkpoint('login')
  const path = '/collections/' + fixture.ids.collection
  await navigate(path)
  await waitFor("document.querySelector('#password') !== null")
  await submit()
  await waitFor("document.querySelector('#settings-title') !== null && [...document.querySelectorAll('button')].some(b=>b.textContent==='編集')")
  await evaluate("[...document.querySelectorAll('button')].find(b=>b.textContent==='編集').focus()")
  await call('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Enter', code: 'Enter', text: '\r', windowsVirtualKeyCode: 13 })
  await call('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13 })
  await waitFor("document.querySelector('#collection-name') !== null")
  await call('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Tab', code: 'Tab', windowsVirtualKeyCode: 9 })
  await call('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Tab', code: 'Tab', windowsVirtualKeyCode: 9 })
  assert.equal(await evaluate('document.activeElement.id'), 'collection-name')
  const set = async (id, value) => evaluate(`{ const e=document.getElementById(${JSON.stringify(id)});e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('input',{bubbles:true}));e.dispatchEvent(new Event('change',{bubbles:true})); }`)
  await set('collection-name', '')
  await click('保存')
  await waitFor("document.querySelector('#collection-name-error') !== null")
  assert.equal(await evaluate('document.activeElement.id'), 'collection-name')
  await set('collection-name', '実画面で編集した架空設定')
  await set('collection-instruction', '実画面の架空編集方針')
  await set('collection-mode', 'days')
  await waitFor("document.querySelector('#collection-days') !== null")
  await set('collection-days', '30')
  await call('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  assert(await evaluate('document.documentElement.scrollWidth<=innerWidth'))
  await call('Emulation.clearDeviceMetricsOverride')
  assert(await evaluate('document.documentElement.scrollWidth<=innerWidth'))
  checkpoint('db-outage')
  stopDB()
  await click('保存')
  await waitFor("document.querySelector('form [role=alert]')?.textContent.includes('保存結果を確認できません')")
  assert.equal(await evaluate("document.querySelector('#collection-name').value"), '実画面で編集した架空設定')
  assert(await evaluate("document.querySelector('fieldset').disabled"))
  startDB()
  checkpoint('response-loss')
  await evaluate("window.updateFetch=window.fetch.bind(window);window.updateRequests=[];window.dropUpdateResponse=true;window.fetch=async(...args)=>{if(args[1]?.method==='PATCH'){window.updateRequests.push({body:args[1].body,key:args[1].headers['Idempotency-Key']});const r=await window.updateFetch(...args);if(window.dropUpdateResponse){window.dropUpdateResponse=false;await r.text();throw new TypeError('fictional lost update response')}return r}return window.updateFetch(...args)}")
  await click('同じ内容で再試行')
  await waitFor("document.querySelector('form [role=alert]')?.textContent.includes('接続できず保存結果')")
  await click('同じ内容で再試行')
  await waitFor("document.querySelector('#edit-title') === null && document.querySelector('main').textContent.includes('実画面で編集した架空設定')")
  assert(await evaluate("window.updateRequests.length===2 && window.updateRequests[0].body===window.updateRequests[1].body && window.updateRequests[0].key===window.updateRequests[1].key"))
  await evaluate('window.fetch=window.updateFetch')
  await navigate(path)
  await waitFor("document.querySelector('main').textContent.includes('実画面で編集した架空設定')")
  await navigate('/collections')
  await waitFor("document.querySelector('main').textContent.includes('実画面で編集した架空設定')")
  await navigate(path)
  await waitFor("[...document.querySelectorAll('button')].some(b=>b.textContent==='編集')")
  await click('編集')
  await set('collection-name', '競合で保持する下書き')
  checkpoint('concurrent-save')
  // A second authenticated client saves the same fetched version first.
  assert.equal(await evaluate(`(async()=>{const r=await fetch('/api${path}');const c=await r.json();const w=await fetch('/api${path}',{method:'PATCH',headers:{'Content-Type':'application/json','Idempotency-Key':crypto.randomUUID()},body:JSON.stringify({name:'別クライアントの架空更新',research_instruction:c.research_instruction,initial_lookback_mode:c.initial_lookback_mode,initial_lookback_days:c.initial_lookback_days,version:c.version})});return w.status})()`), 200)
  await click('保存')
  await waitFor("[...document.querySelectorAll('button')].some(b=>b.textContent==='最新値を確認')")
  assert.equal(await evaluate("document.querySelector('#collection-name').value"), '競合で保持する下書き')
  await click('最新値を確認')
  await waitFor("document.querySelector('.latest-settings')?.textContent.includes('別クライアントの架空更新')")
  assert.equal(await evaluate("document.querySelector('#collection-name').value"), '競合で保持する下書き')
  await click('最新値で編集し直す')
  assert.equal(await evaluate("document.querySelector('#collection-name').value"), '別クライアントの架空更新')
  await set('collection-name', '競合解決後の架空設定')
  await click('保存')
  await waitFor("document.querySelector('#edit-title')===null && document.querySelector('main').textContent.includes('競合解決後の架空設定')")
  await click('編集')
  checkpoint('session-expiry')
  await set('collection-name', '失効で消す編集')
  assert.equal(await evaluate("(async()=> (await fetch('/api/logout',{method:'POST'})).status)()"), 204)
  await click('保存')
  await waitFor("document.querySelector('#password') !== null")
  assert(!(await evaluate("document.querySelector('main').textContent.includes('失効で消す編集')")))
  await submit()
  await waitFor("[...document.querySelectorAll('button')].some(b=>b.textContent==='編集')")
  await click('編集')
  await set('collection-name', 'ログアウトで消す編集')
  const issuedToken = await token()
  await click('ログアウト')
  await waitFor("document.querySelector('#password') !== null")
  assert(!(await evaluate("document.querySelector('#collection-name') !== null || document.querySelector('main').textContent.includes('ログアウトで消す編集')")))
  assert(await evaluate('localStorage.length===0 && sessionStorage.length===0'))
  console.log('Update browser: validation/keyboard/focus, PC/mobile, actual DB outage, committed response loss/replay, detail/list/reload, competing client/manual restart session expiry and logout clearing: passed')
  return issuedToken
}
