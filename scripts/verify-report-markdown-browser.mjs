// Called only from the disposable fixture runner; never print report bodies or credentials.
import assert from 'node:assert/strict'
export const verifyMarkdown = async ({ checkpoint, call, evaluate, waitFor, navigate, click, submit, fixture, token, networkRequests, externalRequests }) => {
  const path = '/reports/' + fixture.ids.markdown_report
  const noExternal = () => {
    assert.equal(externalRequests.length, 0, 'Report attempted an external request')
    assert(networkRequests.every(url => new URL(url).origin === fixture.origin), 'Unexpected network destination')
  }
  checkpoint('protected-return')
  await navigate(path)
  await waitFor("document.querySelector('#password')!==null")
  assert.equal(await evaluate('location.pathname+location.search'), '/login?return_to='+encodeURIComponent(path))
  await submit()
  await waitFor("document.querySelector('.report-body h1')?.textContent==='架空Markdown Report'")
  assert.equal(await evaluate('location.pathname'), path)
  const original = await evaluate(`(async()=> (await(await fetch('/api${path}')).json()).body_markdown)()`)
  const inspect = async () => {
    assert(await evaluate("document.querySelector('.report-body strong')?.textContent==='重要な事実' && document.querySelector('.report-body em')?.textContent==='補足'"))
    assert(await evaluate("document.querySelector('.report-body ul li')?.textContent==='架空の箇条書き' && document.querySelector('.report-body ol')?.getAttribute('start')==='3'"))
    assert(await evaluate("document.querySelectorAll('.report-body pre code').length===2 && document.querySelector('.report-body code').textContent==='inline <code>'"))
    assert(await evaluate("document.querySelector('.report-body').textContent.includes('<script>window.reportExecuted=true</script>') && document.querySelector('.report-body').textContent.includes('画像の代替テキスト') && window.reportExecuted===undefined"))
    assert(await evaluate("document.querySelector('.report-body img,.report-body svg,.report-body math,.report-body iframe,.report-body script,.report-body object,.report-body style,.report-body video')===null"))
    assert(await evaluate("[...document.querySelectorAll('.report-body a')].every(a=>{const u=new URL(a.href);return ['http:','https:'].includes(u.protocol) && !u.username && !u.password && a.getAttribute('rel')==='noopener noreferrer' && a.getAttribute('referrerpolicy')==='no-referrer' && !a.hasAttribute('target') && !a.hasAttribute('ping')})"))
    assert.equal(await evaluate("document.querySelectorAll('.report-body a[href]').length"), 2)
    assert(await evaluate("[...document.querySelectorAll('.report-body *')].every(e=>[...e.attributes].every(a=>(e.tagName==='A'?['href','rel','referrerpolicy']:e.tagName==='OL'?['start']:[]).includes(a.name)))"))
  }
  checkpoint('safe-display-no-network')
  await inspect()
  await call('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true})
  assert(await evaluate('document.documentElement.scrollWidth<=innerWidth'))
  await call('Emulation.clearDeviceMetricsOverride')
  await evaluate('new Promise(resolve=>setTimeout(resolve,400))')
  noExternal()
  checkpoint('reload')
  await navigate(path)
  await waitFor("document.querySelector('.report-body h1')?.textContent==='架空Markdown Report'")
  await inspect()
  assert.equal(await evaluate(`(async()=> (await(await fetch('/api${path}')).json()).body_markdown)()`), original)
  // Delay a real successful Report response; resource clearing must remove both
  // source data and derived HTML, then discard it after route/logout changes.
  checkpoint('reload-clearing-and-late-route')
  await evaluate(`window.markdownFetch=window.fetch.bind(window);window.pauseReport=true;window.fetch=async(...args)=>{const response=await window.markdownFetch(...args);if(args[0]==='/api${path}'&&window.pauseReport){window.pauseReport=false;return new Promise(resolve=>{window.releaseReport=()=>resolve(response)})}return response}`)
  await evaluate("window.dispatchEvent(new PageTransitionEvent('pageshow',{persisted:true}))")
  await waitFor("typeof window.releaseReport==='function'")
  assert(await evaluate("document.querySelector('.report-body')===null"))
  await evaluate("document.querySelector('nav a[href=\"/me\"]').click()")
  await waitFor("location.pathname==='/me' && document.querySelector('#current-user-title')!==null")
  await evaluate('window.releaseReport();window.releaseReport=undefined')
  await evaluate('new Promise(resolve=>setTimeout(resolve,150))')
  assert(await evaluate("document.querySelector('.report-body')===null && !document.querySelector('main').textContent.includes('架空Markdown Report')"))
  checkpoint('logout-and-late-read')
  await navigate(path)
  await waitFor("document.querySelector('.report-body h1')!==null")
  await evaluate(`window.markdownFetch=window.fetch.bind(window);window.pauseReport=true;window.fetch=async(...args)=>{const response=await window.markdownFetch(...args);if(args[0]==='/api${path}'&&window.pauseReport){window.pauseReport=false;return new Promise(resolve=>{window.releaseReport=()=>resolve(response)})}return response};window.dispatchEvent(new PageTransitionEvent('pageshow',{persisted:true}))`)
  await waitFor("typeof window.releaseReport==='function'")
  const issued = await token()
  await click('ログアウト')
  await waitFor("document.querySelector('#password')!==null")
  await evaluate('window.releaseReport();window.releaseReport=undefined')
  await evaluate('new Promise(resolve=>setTimeout(resolve,150))')
  assert(await evaluate("document.querySelector('.report-body')===null && localStorage.length===0 && sessionStorage.length===0"))
  checkpoint('resource-401')
  await navigate(path)
  await waitFor("document.querySelector('#password')!==null")
  await submit()
  await waitFor("document.querySelector('.report-body h1')!==null")
  assert.equal(await evaluate("(async()=> (await fetch('/api/logout',{method:'POST'})).status)()"),204)
  await evaluate("window.dispatchEvent(new PageTransitionEvent('pageshow',{persisted:true}))")
  await waitFor("document.querySelector('#password')!==null")
  assert(await evaluate("document.querySelector('.report-body')===null"))
  noExternal()
  console.log('Markdown browser: deep URL/login return, headings/emphasis/lists/code/links, raw HTML and image safety, per-tag attributes, no external network attempts (intercepted guard), mobile/reload, exact saved API body, clearing/late responses/401/logout: passed')
  return issued
}
